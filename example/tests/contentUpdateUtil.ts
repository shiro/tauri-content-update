/** the plugin's default `readyTimeout` */
export const READY_TIMEOUT = 10_000;
/** tauri's frontendDist, stamped by `content-update bundle` in `pnpm build:app` and embedded into the app */
export const BUILTIN_DIR = path.resolve(
  import.meta.dirname,
  "../.output/public",
);
/** the bindings of the app's commands, generated by src-tauri/build.rs */
const BINDINGS = path.resolve(import.meta.dirname, "../src/native.gen.ts");

/**
 * The id the generated binding of an app command calls it with (`native-api:<command>:<hash>`): code
 * containing it uses the command, as far as `content-update bundle` is concerned. `hash` overrides the
 * signature hash, e.g. to pretend the bundle was built against another signature.
 */
export function appCommand(name: string, hash?: string) {
  const id = fs
    .readFileSync(BINDINGS, "utf-8")
    .match(new RegExp(`native-api:${name}:[0-9a-f]{12}`))?.[0];
  if (!id) throw new Error(`no binding for the command ${name} in ${BINDINGS}`);
  return hash ? `native-api:${name}:${hash}` : id;
}

export const delay = (ms: number) => new Promise((r) => setTimeout(r, ms));

export async function waitFor<T>(
  fn: () => T | undefined | Promise<T | undefined>,
  what: string,
  timeout = 60_000,
): Promise<T> {
  const end = Date.now() + timeout;
  while (true) {
    const v = await fn();
    if (v) return v;
    if (Date.now() > end) throw new Error(`timed out waiting for ${what}`);
    await delay(250);
  }
}


export async function expectRejected(
  p: Promise<unknown>,
  code: string,
  message?: RegExp,
) {
  const err = await p.then(
    () => undefined,
    (e) => e,
  );
  expect(err, `expected a ${code} rejection`).toBeDefined();
  expect(err.code).toBe(code);
  if (message) expect(err.message).toMatch(message);
}

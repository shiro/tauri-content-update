// update server

type Handler = (req: http.IncomingMessage, res: http.ServerResponse) => void;

export class UpdateServer {
  readonly blobs = fs.mkdtempSync(
    path.join(os.tmpdir(), "content-update-blobs-"),
  );
  /** request paths, in order */
  requests: string[] = [];
  private manifests = new Map<string, Handler>();
  private faults = new Map<string, Handler[]>();
  private server = http.createServer((req, res) => this.handle(req, res));

  constructor(readonly port: number) {}

  listen() {
    return new Promise<void>((r) =>
      this.server.listen(this.port, "127.0.0.1", r),
    );
  }

  close() {
    this.server.closeAllConnections();
    fs.rmSync(this.blobs, { recursive: true, force: true });
    return new Promise<void>((r) => this.server.close(() => r()));
  }

  url(channel: string) {
    return `http://localhost:${this.port}/${channel}/manifest.json`;
  }

  /** publishes a manifest (object or raw text) on a channel */
  publish(channel: string, manifest: Manifest | string | Handler) {
    this.manifests.set(
      channel,
      typeof manifest == "function"
        ? manifest
        : (_, res) => {
            res.writeHead(200, { "content-type": "application/json" });
            res.end(
              typeof manifest == "string" ? manifest : JSON.stringify(manifest),
            );
          },
    );
  }

  /** the next requests of a blob are handled by `handlers` (one each) instead */
  fault(sha256: string, ...handlers: Handler[]) {
    this.faults.set(sha256, handlers);
  }

  /** blobs requested since the last reset */
  blobRequests() {
    return this.requests
      .filter((p) => p.includes("/files/"))
      .map((p) => p.split("/files/")[1]);
  }

  private handle(req: http.IncomingMessage, res: http.ServerResponse) {
    const url = new URL(req.url!, "http://x");
    this.requests.push(url.pathname);
    const [, channel, kind, sha] = url.pathname.split("/");
    if (kind == "manifest.json") {
      const h = this.manifests.get(channel);
      if (h) return h(req, res);
    } else if (kind == "files" && /^[0-9a-f]{64}$/.test(sha)) {
      const fault = this.faults.get(sha)?.shift();
      if (fault) return fault(req, res);
      const file = path.join(this.blobs, "files", sha);
      if (fs.existsSync(file)) {
        res.writeHead(200, { "content-type": "application/octet-stream" });
        return fs.createReadStream(file).pipe(res);
      }
    }
    res.writeHead(404).end("not found");
  }
}


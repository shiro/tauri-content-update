export const SHARED_JS = `document.getElementById("js").textContent = "shared.js loaded";\n`;
// identical in every test bundle, so it is never downloaded twice
export const BIG = crypto
  .createHash("sha256")
  .update("seed")
  .digest()
  .toString("hex")
  .repeat(8 * 1024); // 512 KiB

export interface BundleOptions {
  /** calls notifyReady on load (default true) */
  ready?: boolean;
  files?: Record<string, string | Buffer>;
  minNativeVersion?: number;
  /** native API ids the bundle uses besides the ones in its code (`plugin:<plugin>|<command>`) */
  nativeApi?: string[];
  /** extra text in index.html, to change it without changing the version */
  salt?: string;
}

export function makeBundle(
  server: UpdateServer,
  version: string,
  {
    ready = true,
    files = {},
    minNativeVersion,
    nativeApi,
    salt = "",
  }: BundleOptions = {},
): Manifest {
  const dir = fs.mkdtempSync(
    path.join(os.tmpdir(), `content-update-${version}-`),
  );
  const all: Record<string, string | Buffer> = {
    "index.html": `<!doctype html>
<html><head><meta charset="utf-8"><title>bundle ${version}</title></head>
<body>
<h1 id="version">${version}</h1>
<div id="js"></div>
<script src="/shared.js"></script>
<script>${ready ? `window.__TAURI_INTERNALS__.invoke("plugin:content-update|notify_ready").then(() => (window.readyAnswered = true));` : ""}</script>
<!-- ${salt} -->
</body></html>
`,
    "shared.js": SHARED_JS,
    "assets/big.txt": BIG,
    ...files,
  };
  for (const [rel, content] of Object.entries(all)) {
    fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true });
    fs.writeFileSync(path.join(dir, rel), content);
  }
  const manifest = createBundle(dir, {
    outDir: server.blobs,
    version,
    minNativeVersion,
    nativeApi,
  });
  fs.rmSync(dir, { recursive: true });
  return manifest;
}


// Creates content-update bundles: a static folder with `manifest.json` and content-addressed `files/<sha256>`.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

/** metadata file written to the root of every bundle (the app's embedded one too) */
export const META = "content-update.json";

const VERSION = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/;

const sha256 = (data) => crypto.createHash("sha256").update(data).digest("hex");

/** hex characters of a native API hash */
export const HASH_LEN = 12;

/**
 * The hash of a native API id, as `tauri-plugin-content-update-build` computes it at the app's build: a plugin
 * command (`plugin:<plugin>|<command>`) or an app command signature.
 */
export const nativeApiHash = (id) => sha256(id).slice(0, HASH_LEN);

// files whose code is scanned for native API use
const CODE = /\.(m?js|cjs|html?)$/;
// a plugin command, as passed to invoke() (by the plugins' JS APIs and @tauri-apps/api)
const PLUGIN_COMMAND = /(?<![\w-])plugin:[\w-]+\|\w+/g;
// an app command called through the bindings generated by tauri-plugin-content-update-build
const APP_COMMAND = new RegExp(
  `native-api:(\\w+):([0-9a-f]{${HASH_LEN}})(?![0-9a-f])`,
  "g",
);

function walk(dir, prefix = "") {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(abs, rel));
    else if (entry.isFile()) out.push(rel);
    else if (entry.isSymbolicLink() && fs.statSync(abs).isFile()) out.push(rel);
  }
  return out;
}

/**
 * The native API a web build uses, as a map hash -> id: the plugin commands named in its code and
 * the app commands it calls through the generated bindings (`native-api:<command>:<hash>`).
 * Commands invoked with computed names can't be seen, pass them as `nativeApi` to createManifest.
 */
export function findNativeApi(srcDir) {
  const found = new Map();
  for (const rel of walk(srcDir).sort()) {
    if (!CODE.test(rel)) continue;
    const code = fs.readFileSync(path.join(srcDir, rel), "utf-8");
    for (const [id] of code.matchAll(PLUGIN_COMMAND))
      found.set(nativeApiHash(id), id);
    for (const [, command, hash] of code.matchAll(APP_COMMAND))
      found.set(hash, command);
  }
  return found;
}

/**
 * Builds the manifest of a web build directory.
 * The version defaults to a hash of the file list, so identical builds get identical versions.
 * `requires` lists the hashes of the native API the bundle uses (findNativeApi + `nativeApi` ids):
 * apps that don't provide all of it don't install the bundle.
 */
export function createManifest(
  srcDir,
  { version, minNativeVersion, nativeApi = [] } = {},
) {
  const files = {};
  for (const rel of walk(srcDir).sort()) {
    if (rel == META) continue;
    const data = fs.readFileSync(path.join(srcDir, rel));
    files[rel] = { sha256: sha256(data), size: data.length };
  }
  if (!files["index.html"]) throw new Error(`${srcDir} has no index.html`);
  version ??= sha256(JSON.stringify(files)).slice(0, 16);
  if (!VERSION.test(version))
    throw new Error(`invalid version '${version}', must match ${VERSION}`);
  const requires = new Set(findNativeApi(srcDir).keys());
  for (const id of nativeApi) requires.add(nativeApiHash(id));
  return {
    version,
    ...(minNativeVersion ? { minNativeVersion: Number(minNativeVersion) } : {}),
    ...(requires.size ? { requires: [...requires].sort() } : {}),
    files,
  };
}

/**
 * Stamps `srcDir/content-update.json` (so the app knows its built-in bundle) and, if `outDir` is given,
 * publishes the bundle there: blobs to `outDir/files/<sha256>` (existing ones are kept, so several
 * versions can share a folder), then `outDir/manifest.json` (written last, atomically).
 */
export function createBundle(srcDir, { outDir, ...options } = {}) {
  const manifest = createManifest(srcDir, options);
  const json = JSON.stringify(manifest, null, 2) + "\n";
  fs.writeFileSync(path.join(srcDir, META), json);
  if (outDir) {
    const filesDir = path.join(outDir, "files");
    fs.mkdirSync(filesDir, { recursive: true });
    for (const [rel, { sha256 }] of Object.entries(manifest.files)) {
      const dst = path.join(filesDir, sha256);
      if (!fs.existsSync(dst)) fs.copyFileSync(path.join(srcDir, rel), dst);
    }
    const tmp = path.join(outDir, `.manifest.json.${process.pid}`);
    fs.writeFileSync(tmp, json);
    fs.renameSync(tmp, path.join(outDir, "manifest.json"));
  }
  return manifest;
}
